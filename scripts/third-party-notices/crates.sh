#!/usr/bin/env bash
# Write scripts/third-party-notices/crates.txt: every crates.io package compiled into a shipped binary, i.e. the
# union of `cargo tree -e normal,build` for the CLI (artificer-cli; Linux with and without --features cuda) and the
# desktop app (artificer-desktop) on the three release targets. One line per crate: "name version scope", where
# scope lists binary:target pairs. Metadata only (no compile); --offline, so it stops if the cargo cache is missing
# something instead of fetching. Run from anywhere inside the repository.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${1:-$ROOT/scripts/third-party-notices/crates.txt}"
WORK="$(mktemp -d "${TMPDIR:-$ROOT/target}/tpn.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT
cd "$ROOT"
declare -A TRIPLE=([linux-x86_64]=x86_64-unknown-linux-gnu [windows-x86_64]=x86_64-pc-windows-msvc [macos-aarch64]=aarch64-apple-darwin)
tree() { # <label> <triple> <package> [features...]
  local label=$1 triple=$2 pkg=$3; shift 3
  cargo tree --offline --locked -e normal,build --target "$triple" -p "$pkg" "$@" --prefix none --format '{p}' \
    > "$WORK/$label.txt"
}
for t in linux-x86_64 windows-x86_64 macos-aarch64; do
  tree "cli:$t" "${TRIPLE[$t]}" artificer-cli
  tree "desktop:$t" "${TRIPLE[$t]}" artificer-desktop
done
tree "cli:linux-x86_64+cuda" x86_64-unknown-linux-gnu artificer-cli --features cuda
python3 - "$WORK" "$OUT" <<'PY'
import sys, os, collections
work, out = sys.argv[1], sys.argv[2]
seen = collections.defaultdict(list)
for f in sorted(os.listdir(work)):
    label = f[:-4]
    for ln in open(os.path.join(work, f)):
        p = ln.split()
        if len(p) < 2 or not p[1].startswith("v") or "(/" in ln or "(file://" in ln:
            continue  # workspace members (path dependencies) and blank lines
        k = (p[0], p[1][1:])
        if label not in seen[k]:
            seen[k].append(label)
cuda_extra = {k for k, ls in seen.items() if "cli:linux-x86_64+cuda" in ls and "cli:linux-x86_64" not in ls}
with open(out, "w") as fh:
    fh.write("# Generated by scripts/third-party-notices/crates.sh from Cargo.lock; do not edit by hand.\n")
    fh.write("# name version scope (binary:target, ...; +cuda = only with the cuda feature)\n")
    for (n, v), ls in sorted(seen.items()):
        ls = sorted(set(l.replace("+cuda", "") for l in ls)) if (n, v) not in cuda_extra else sorted(ls)
        fh.write(f"{n} {v} {','.join(ls)}\n")
print(f"{len(seen)} crates; cuda feature adds {len(cuda_extra)}", file=sys.stderr)
PY
